def emotion_prompt(emotion: str, confidence: float, lang: str = "ru") -> str:
    """Возвращает инструкцию для модели на основе эмоции."""
    if not emotion or confidence < 0.28:
        return ""
    table = EMOTION_PROMPTS.get(lang, EMOTION_PROMPTS["ru"])
    return table.get(emotion, "")


# ── Анализ тона голоса (pitch + energy) ──
def analyze_voice_tone(pitch: float, energy: float, speech_rate: float) -> dict:
    """
    Анализирует голос:
      pitch — высота (Гц), energy — громкость (0-1), speech_rate — темп (слов/сек)
    Возвращает предполагаемое эмоциональное состояние.
    """
    signals = []
    emo = "neutral"
    conf = 0.3

    # Адаптивные пороги: женщины ~200Гц, мужчины ~120Гц
    # Используем относительные отклонения вместо абсолютных
    _mid = 170  # средний ориентир
    _high = _mid * 1.3   # ~221
    _low  = _mid * 0.85  # ~145

    # Высокий pitch + быстрый темп → возбуждение/тревога
    if pitch > _high and speech_rate > 2.8:
        emo = "fearful" if energy < 0.5 else "surprised"
        conf = 0.55
        signals.append("высокий голос, быстрая речь")
    # Низкий pitch + медленный темп → грусть/усталость
    elif pitch < _low and speech_rate < 2.2:
        emo = "sad"
        conf = 0.5
        signals.append("низкий голос, медленная речь")
    # Резкая громкая быстрая речь → злость (ДОЛЖНА быть ВЫШЕ happy!)
    elif energy > 0.75 and speech_rate > 3.2:
        emo = "angry"
        conf = 0.55
        signals.append("громкая быстрая речь")
    # Высокая энергия + средний pitch → радость
    elif energy > 0.65 and 160 < pitch < 260:
        emo = "happy"
        conf = 0.5
        signals.append("энергичный голос")

    return {"emotion": emo, "confidence": conf, "signals": signals}


def fuse_emotions(face_emo: str, face_conf: float,
                  voice_emo: str, voice_conf: float) -> dict:
    """
    Сливает эмоцию с лица (DeepFace) и голоса.
    Если оба согласны — высокая уверенность.
    Если расходятся — берём более уверенный сигнал.
    """
    if face_emo == voice_emo and face_emo != "neutral":
        # Оба согласны — усиливаем
        return {"emotion": face_emo,
                "confidence": min(0.98, (face_conf + voice_conf) / 2 + 0.25),
                "source": "face+voice"}
    # Расходятся — берём более уверенный
    if face_conf >= voice_conf:
        return {"emotion": face_emo, "confidence": face_conf, "source": "face"}
    return {"emotion": voice_emo, "confidence": voice_conf, "source": "voice"}