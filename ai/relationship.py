# -*- coding: utf-8 -*-
"""
VIVLOS — Relationship System.
Отслеживает уровень отношений между пользователем и каждым AI-персонажем.
Чем больше общаются — тем теплее и ближе становится AI.
"""


def relationship_prompt(level: int, trust: int, lang: str = "ru") -> str:
    """
    Генерирует инструкцию о том, как близко AI должен общаться,
    в зависимости от уровня отношений.

    level: 0-100 (общий уровень знакомства)
    trust: 0-100 (доверие)
    """
    if lang == "kk":
        if level < 10:
            return "\n[ҚАРЫМ-ҚАТЫНАС: жаңа таныс]\nСыпайы бол, бірақ жылы. Әлі жақын емессіңдер."
        elif level < 35:
            return "\n[ҚАРЫМ-ҚАТЫНАС: таныс]\nЕркінірек сөйле. Бұрынғы әңгімелерді есте сақта."
        elif level < 70:
            return "\n[ҚАРЫМ-ҚАТЫНАС: дос]\nЖақын дос ретінде сөйле. Әзілдес, ішкі әзілдер қолдан."
        else:
            return "\n[ҚАРЫМ-ҚАТЫНАС: жақын дос]\nҰзақ жылдық дос сияқты. Толық сен, жылы, ашық."
    else:
        if level < 10:
            return "\n[ОТНОШЕНИЯ: новое знакомство]\nБудь вежливым но тёплым. Вы ещё не близки."
        elif level < 35:
            return "\n[ОТНОШЕНИЯ: знакомый]\nГовори свободнее. Помни прошлые разговоры. Можно лёгкий юмор."
        elif level < 70:
            return "\n[ОТНОШЕНИЯ: друг]\nОбщайся как близкий друг. Шути, используй внутренние шутки, будь искренним."
        else:
            return "\n[ОТНОШЕНИЯ: близкий друг]\nКак друг на много лет. Полное доверие, тепло, открытость, можешь поддразнивать."


def calc_relationship_gain(message_count: int, emotion_shared: bool) -> dict:
    """
    Сколько очков отношений начислить за взаимодействие.
    Эмоциональные разговоры сближают быстрее.
    """
    base = 1
    if emotion_shared:
        base += 2  # делился чувствами — сближает
    if message_count > 10:
        base += 1  # долгий разговор
    return {"level_gain": base, "trust_gain": base if emotion_shared else 0}


def relationship_label(level: int, lang: str = "ru") -> str:
    """Текстовая метка уровня для UI."""
    labels = {
        "ru": [(70, "💛 Близкий друг"), (35, "😊 Друг"),
               (10, "🙂 Знакомый"), (0, "👋 Новичок")],
        "kk": [(70, "💛 Жақын дос"), (35, "😊 Дос"),
               (10, "🙂 Таныс"), (0, "👋 Жаңа")],
    }
    for threshold, label in labels.get(lang, labels["ru"]):
        if level >= threshold:
            return label
    return labels[lang][-1][1]